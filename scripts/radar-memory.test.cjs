const assert=require('node:assert/strict');
const {RADAR_QUERIES}=require('../.market-test-build/radar-query-plan.js');
const {buildQueryMemory,chooseNextQueries,buildCompetitorMatrix}=require('../.market-test-build/radar-memory.js');
const now=new Date('2026-11-15T12:00:00Z');
const q=RADAR_QUERIES.ar[0].query;
const observations=[{competitor_id:'x',language:'ar',query:q,rank:1,observed_at:'2026-11-15T10:00:00Z'},{competitor_id:'z',language:'ar',query:q,rank:2,observed_at:'2026-11-15T10:00:00Z'}];
const memory=buildQueryMemory(observations,now);
assert.equal(memory.length,24);
assert.equal(memory.find(x=>x.query===q).competitor_count,2);
assert.equal(memory.find(x=>x.query===q).best_rank,1);
const chosen=chooseNextQueries(memory,1,now);
assert.equal(chosen.length,3);
assert.notEqual(chosen.find(x=>x.language==='ar').query,q);
const matrix=buildCompetitorMatrix(observations);
assert.equal(matrix.length,2);
assert.equal(matrix[0].angles.length,1);
assert.equal(matrix[0].best_rank,1);
const empty=buildQueryMemory([],now);
const daily=Array.from({length:8},(_,i)=>chooseNextQueries(empty,1,new Date(now.getTime()+i*86400000))[0].query);
assert.equal(new Set(daily).size,8,'Uncovered queries must rotate instead of getting stuck');
const arbitraryQuery = RADAR_QUERIES.ar[0].query;
const zeroResultAttempt = {language:'ar',query:arbitraryQuery,attempted_at:'2026-11-15T12:00:00Z'};
const withAttempt = buildQueryMemory([],now,[zeroResultAttempt]);
assert.equal(withAttempt.find(x=>x.query===arbitraryQuery && x.language==='ar').attempt_count,1);
assert.notEqual(chooseNextQueries(withAttempt,1,now).find(x=>x.language==='ar').query,arbitraryQuery,'Do not repeat searches that returned zero candidates');
console.log('Radar memory: stale priority, competitor matrix, rotation passed');
