'use strict';
const assert=require('node:assert/strict');
const {parseConsent,publicPage,validateInvestorSignal}=require('../.investor-test-build/investor-events.js');
const consent={version:2,necessary:true,analytics:true,marketing:false};
assert(parseConsent(JSON.stringify(consent)));
assert(parseConsent(encodeURIComponent(JSON.stringify(consent))));
assert(!parseConsent(JSON.stringify({...consent,version:1})));
assert(!parseConsent(JSON.stringify({...consent,analytics:false})));
assert(!parseConsent('bad'));
assert.equal(publicPage('/en/services/company-formation'),'company-formation');
assert.equal(publicPage('/zh/insights/a-guide'),'insight');
assert.equal(publicPage('/ar/admin'),null);
assert.equal(publicPage('/admin/dashboard'),null);
assert.equal(publicPage('/en/packages?phone=123'),null);
const signal={event:'whatsapp_click',page:'home',locale:'ar'};
assert.deepEqual(validateInvestorSignal(signal),signal);
assert.equal(validateInvestorSignal({...signal,phone:'123'}),null);
assert.equal(validateInvestorSignal({...signal,page:'/en/insights/test'}),null);
assert.equal(validateInvestorSignal({...signal,event:'lead_saved'}),null);
console.log('PASS closed vocabulary and explicit fresh analytics consent');
