'use strict';
const assert=require('node:assert/strict');
const {PROVIDERS,METRICS,permittedUnits,quotaDecision,usageDateUtc,reservationKey}
 =require('./v3-provider-quota-contract.cjs');
assert.deepEqual(PROVIDERS,['exa','tavily','parallel','firecrawl','groq','gemini','nvidia','openrouter']);
assert.deepEqual(METRICS,['requests','tokens']);
assert.equal(permittedUnits(50),40);
assert.equal(permittedUnits(100),80);
assert.equal(permittedUnits(3),2);
assert.equal(permittedUnits(1),0);
assert.equal(permittedUnits(undefined),null);
assert.equal(quotaDecision({provider:'exa',metric:'requests',limit:50,used:39,amount:1,verified:true}).status,'reservation_eligible');
assert.equal(quotaDecision({provider:'exa',metric:'requests',limit:50,used:39,amount:2,verified:true}).status,'quota_reached');
assert.equal(quotaDecision({provider:'exa',metric:'requests',limit:50,used:40,amount:1,verified:true}).status,'quota_reached');
assert.equal(quotaDecision({provider:'groq',metric:'tokens',limit:200000,used:159000,amount:2000,verified:true}).status,'quota_reached');
assert.equal(quotaDecision({provider:'groq',metric:'tokens',limit:200000,used:159000,amount:1000,verified:true}).status,'reservation_eligible');
assert.equal(quotaDecision({provider:'gemini',limit:50,used:0,amount:1,verified:false}).reason,'account_specific_daily_limit_unverified');
assert.equal(quotaDecision({provider:'unknown',limit:999999,used:0,verified:true}).status,'unconfigured');
assert.equal(quotaDecision({provider:'tavily',limit:0,used:0,verified:true}).status,'unconfigured');
assert.equal(quotaDecision({provider:'tavily',limit:50,used:-1,verified:true}).status,'unconfigured');
assert.equal(quotaDecision({provider:'tavily',limit:50,used:0,amount:0,verified:true}).status,'unconfigured');
assert.equal(quotaDecision({provider:'tavily',limit:50,used:0,verified:true}).granted,false,'pure local check is not an atomic reservation');
assert.equal(usageDateUtc('2026-11-20T23:59:59Z'),'2026-11-20');
assert.equal(usageDateUtc('2026-11-21T00:00:00Z'),'2026-11-21');
assert.equal(reservationKey({githubRunId:'44750000101',stage:'zh-draft-1',provider:'groq',sequence:3}),'44750000101:zh-draft-1:groq:3');
assert.equal(reservationKey({githubRunId:'44750000101',stage:'zh-draft-1',provider:'groq',sequence:4}),'44750000101:zh-draft-1:groq:4');
assert.equal(reservationKey({githubRunId:'bad-run',stage:'draft',provider:'exa',sequence:1}),null);
assert.equal(reservationKey({githubRunId:'44750000101',stage:'draft',provider:'bad',sequence:1}),null);
console.log('PASS phase2 provider quota proposal: strict 80%, daily UTC rollover, unverified caps fail closed and pure decisions never grant a live call');
